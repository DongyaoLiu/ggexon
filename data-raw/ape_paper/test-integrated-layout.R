suppressPackageStartupMessages(library(testthat))
base <- normalizePath(if (dir.exists("results")) "results" else "data-raw/ape_paper/results")
for (case in c("mhc")) local({
  example <- case
  test_that(paste(example, "keeps only genome annotation and nucleotide-link panels"), {
    w <- read.delim(file.path(base, example, "windows.tsv"))
    layout <- read.delim(file.path(base, "figures", paste0(example, ".layout-qc.tsv")))
    expect_equal(sum(layout$panel_type == "annotation"), nrow(w))
    expect_equal(sum(layout$panel_type == "coverage"), 0L)
    expect_equal(sum(layout$panel_type == "link"), nrow(w) - 1L)
    expect_identical(as.character(layout$track[layout$panel_type == "annotation"]), as.character(w$id))
  })
  test_that(paste(example, "keeps interval annotations below its own gene models"), {
    qc <- read.delim(file.path(base, "figures", paste0(example, ".feature-lane-qc.tsv")))
    expect_true(all(qc$panel_type=="annotation"))
    expect_true(all(qc$ymax<0))
    expect_true(all(qc$ymin<qc$ymax))
  })
  test_that(paste(example, "retains source signals as below-gene lanes on their own genome"), {
    file <- file.path(base, "figures", paste0(example, ".signal-lane-qc.tsv"))
    expect_true(file.exists(file))
    if (!file.exists(file)) return(invisible(NULL))
    qc <- read.delim(file)
    w <- read.delim(file.path(base, example, "windows.tsv"))
    expect_true(all(qc$track %in% w$id))
    expect_true(all(qc$panel_type == "annotation"))
    expect_true(all(qc$lane_top < 0))
    expect_equal(qc$input_intervals, qc$built_intervals)
    expect_equal(qc$input_score_sum, qc$built_score_sum, tolerance=1e-12)
    expect_true(all(qc$exact_score_match))
    expect_true(all(qc$raw_coordinate_match))
    expect_true(all(qc$scale_max > qc$scale_min))
    if (example == "mhc") expect_false("chimp_h2" %in% qc$track)
  })
})
